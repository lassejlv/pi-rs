//! `node:zlib` on zlib-rs: dictionaries (deflate/inflate/raw, Z_NEED_DICT errors), windowBits,
//! memLevel, strategies, params() mid-stream, gzip members, option validation and zlib's error
//! messages. Expected output is Node 22's (compressed bytes are compared where zlib and
//! Chromium's zlib agree).

use std::process::Command;

const NODE_BIN: &str = env!("CARGO_BIN_EXE_pi-jsrt-node");

#[test]
fn zlib_options_match_node() {
    let dir = tempfile::tempdir().unwrap();
    let path = dir.path().join("zlib.js");
    std::fs::write(&path, SCRIPT).unwrap();
    let out = Command::new(NODE_BIN).arg(&path).output().unwrap();
    // Node's gzip OS byte is Darwin on macOS; these hashes were independently
    // generated by running SCRIPT with Node on macOS. The other vectors agree.
    let expected=if cfg!(target_os="macos") {
        EXPECTED.replace("d88e522f4970","97c8f29a589b").replace("b3678c4d764c","8ba8505b8577").replace("ed2d70033686","efc8b6e6a78d")
    } else { EXPECTED.to_owned() };
    assert_eq!(format!("{}{}", String::from_utf8_lossy(&out.stdout), String::from_utf8_lossy(&out.stderr)), expected);
}

